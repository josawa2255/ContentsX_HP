def validate(services: list[dict], groups: list[dict]) -> None:
    if not isinstance(services, list) or not isinstance(groups, list):
        raise ValueError("services and groups must be arrays")
    required = {"id", "slug", "group", "name", "eyebrow", "shortCopy", "hoverSummary", "tags", "icon", "href", "destination", "featured"}
    group_ids: set[str] = set()
    for group in groups:
        if not isinstance(group, dict) or not all(group.get(key) for key in ("id", "name", "tagline", "summary")):
            raise ValueError(f"invalid group: {group!r}")
        if not SLUG.fullmatch(group["id"]) or group["id"] in group_ids:
            raise ValueError(f"invalid or duplicate group: {group['id']!r}")
        group_ids.add(group["id"])
    ids: set[str] = set()
    slugs: set[str] = set()
    for service in services:
        if not isinstance(service, dict) or not required.issubset(service):
            raise ValueError(f"service missing required fields: {service!r}")
        service_id, slug = service["id"], service["slug"]
        if not SLUG.fullmatch(service_id) or service_id in ids:
            raise ValueError(f"invalid or duplicate service id: {service_id!r}")
        if not SLUG.fullmatch(slug) or slug in slugs:
            raise ValueError(f"invalid or duplicate slug: {slug!r}")
        if service["group"] not in group_ids:
            raise ValueError(f"unknown group for {service_id}: {service['group']!r}")
        if service["href"] != f"/services/{slug}/":
            raise ValueError(f"href must match slug for {service_id}")
        destination = service["destination"]
        parsed = urlsplit(destination) if isinstance(destination, str) else None
        approved_host = parsed and parsed.scheme == "https" and (parsed.hostname == "contentsx.jp" or (parsed.hostname or "").endswith(".contentsx.jp"))
        if destination != f"/services/#{slug}" and not approved_host:
            raise ValueError(f"invalid destination for {service_id}: {destination!r}")
        if not (ROOT / "material" / "web-system" / "icons" / f"{service['icon']}.svg").is_file():
            raise ValueError(f"unknown icon for {service_id}: {service['icon']!r}")
        if not all(isinstance(service[key], str) and service[key].strip() for key in ("name", "eyebrow", "shortCopy", "hoverSummary")):
            raise ValueError(f"empty text field for {service_id}")
        if not isinstance(service["tags"], list) or not all(isinstance(tag, str) and tag for tag in service["tags"]):
            raise ValueError(f"invalid tags for {service_id}")
        if not isinstance(service["featured"], bool):
            raise ValueError(f"invalid featured for {service_id}")
        for field in ("features", "challenges", "steps", "useCases"):
            if field in service and (not isinstance(service[field], list) or not all(isinstance(item, str) and item for item in service[field])):
                raise ValueError(f"invalid {field} for {service_id}")
        for faq in service.get("faqs", []):
            if not isinstance(faq, dict) or not faq.get("question") or not faq.get("answer"):
                raise ValueError(f"invalid FAQ for {service_id}")
        for field in ("image", "hoverImage"):
            if field not in service:
                continue
            image = service[field]
            if not isinstance(image, str) or not IMAGE_PATH.fullmatch(image):
                raise ValueError(f"invalid {field} for {service_id}")
            image_path = (ROOT / image.lstrip("/")).resolve()
            if not image_path.is_relative_to(ROOT / "material") or not image_path.is_file():
                raise ValueError(f"missing or unsafe {field} for {service_id}")
        ids.add(service_id)
        slugs.add(slug)


def render_template(name: str, values: dict[str, str]) -> str:
    result = (TEMPLATES / name).read_text(encoding="utf-8")
    for key, value in values.items():
        result = result.replace("{{" + key + "}}", value)
    remaining = PLACEHOLDER.findall(result)
    if remaining:
        raise ValueError(f"unfilled template values: {remaining}")
    return result


def render_icon(name: str, class_name: str = "cxs-icon") -> str:
    source = (ROOT / "material" / "web-system" / "icons" / f"{name}.svg").read_text(encoding="utf-8").strip()
    return source.replace("<svg ", f'<svg class="{class_name}" aria-hidden="true" focusable="false" ', 1)


